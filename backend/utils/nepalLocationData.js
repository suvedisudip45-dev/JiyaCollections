/**
 * Resolves any string location (name or code) to its canonical LocationMapping entry
 */
export const resolveLocationEntry = (query) => {
  if (!query) return null;
  const raw = String(query).trim().toUpperCase();
  if (CODE_INDEX.has(raw)) return CODE_INDEX.get(raw);
  const cleaned = cleanStr(query);
  if (NAME_INDEX.has(cleaned)) return NAME_INDEX.get(cleaned);
  // Partial search
  for (const loc of NEPAL_LOCATION_MAP) {
    if (cleanStr(loc.name).includes(cleaned) || cleaned.includes(cleanStr(loc.name))) {
      return loc;
    }
  }
  return null;
};

/**
 * Get 4-character code for campaign scope / target
 */
export const get4CharCodeForCampaign = (campaign) => {
  if (campaign.targetScopeType === "DISTRICT") {
    const loc = resolveLocationEntry(campaign.targetDistrict);
    if (loc && loc.code) return loc.code;
    const fallback = String(campaign.targetDistrict || "DIS").toUpperCase().replace(/[^A-Z0-9]/g, "");
    return (fallback.length >= 4 ? fallback.slice(0, 4) : fallback.padEnd(4, "0"));
  }
  if (campaign.targetScopeType === "PROVINCE") {
    const loc = resolveLocationEntry(campaign.targetProvince);
    if (loc && loc.code) return loc.code;
    const fallback = String(campaign.targetProvince || "PRO").toUpperCase().replace(/[^A-Z0-9]/g, "");
    return (fallback.length >= 4 ? fallback.slice(0, 4) : fallback.padEnd(4, "0"));
  }
  return "NATW";
};
