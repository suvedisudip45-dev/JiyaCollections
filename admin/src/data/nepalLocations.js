// Calculate Haversine distance in km
export const calculateDistance = (lat1, lon1, lat2, lon2) => {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
};

// Find nearest Nepal city given lat/lng
export const findNearestNepalCity = (lat, lng) => {
  if (!lat || !lng) return NEPAL_CITIES[0];
  let nearest = NEPAL_CITIES[0];
  let minDistance = Infinity;

  for (const city of NEPAL_CITIES) {
    const dist = calculateDistance(lat, lng, city.lat, city.lng);
    if (dist < minDistance) {
      minDistance = dist;
      nearest = city;
    }
  }

  return { ...nearest, distanceKm: Math.round(minDistance) };
};

// Lookup city info by name
export const getCityInfo = (cityName) => {
  if (!cityName) return null;
  return (
    NEPAL_CITIES.find(
      (c) => c.name.toLowerCase() === cityName.toLowerCase() || c.name.toLowerCase().includes(cityName.toLowerCase())
    ) || null
  );
};
